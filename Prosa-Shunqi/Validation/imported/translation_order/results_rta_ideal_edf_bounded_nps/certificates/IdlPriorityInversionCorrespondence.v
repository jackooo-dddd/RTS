Lemma pi_has_canonical (T : Type) (PR : T -> bool) (PL : T -> I.Bool) :
  ArPredRel PR PL ->
  forall xs : seq T, ArBoolRel (has PR xs) (I.List_any T (ar_list_to_imported xs) PL).
Proof.
  intros HP xs. induction xs as [|x xs IH].
  - exact (@Lean.eq_refl _ _).
  - exact (pi_bool_or_related _ _ _ _ (HP x) IH).
Qed.

Lemma pi_has_related (T : Type) (PR : T -> bool) (PL : T -> I.Bool)
