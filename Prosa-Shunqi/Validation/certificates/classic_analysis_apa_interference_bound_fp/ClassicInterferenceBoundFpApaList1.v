(** * Membership, uniqueness, index (eqTypes) *)

Section Eq.
Variables (A : eqType) (B : Type) (c : A -> B) (d : B -> A).
Hypothesis Hdc : forall x, Logic.eq (d (c x)) x.
Hypothesis Hcd : forall y, Logic.eq (c (d y)) y.

Lemma cl1_c_inj x y : Logic.eq (c x) (c y) -> Logic.eq x y.
Proof. move=> E. by rewrite -(Hdc x) -(Hdc y) E. Qed.

Definition cl1_false_elim_s (Q : SProp) (H : is_true false) : Q :=
  match (Bool.diff_false_true H) return Q with end.

Fixpoint cl1_mem_forward (x : A) (s : seq A) {struct s} : x \in s -> I.List_Mem_inst1 B (c x) (cl1_map c s) :=
  match s as s0 return x \in s0 -> I.List_Mem_inst1 B (c x) (cl1_map c s0) with
  | [::] => fun H => cl1_false_elim_s _ H
  | y :: s' =>
      match @eqP A x y in reflect _ b return (b || (x \in s')) -> I.List_Mem_inst1 B (c x) (I.List_cons_inst1 B (c y) (cl1_map c s')) with
      | ReflectT E => fun _ =>
          match E in Logic.eq _ z return I.List_Mem_inst1 B (c x) (I.List_cons_inst1 B (c z) (cl1_map c s')) with
          | Logic.eq_refl => I.List_Mem_head_inst1 B (c x) _
          end
      | ReflectF _ => fun H => I.List_Mem_tail_inst1 B (c x) (c y) _ (cl1_mem_forward x s' H)
      end
  end.

Fixpoint cl1_mem_backward (a : B) (l : I.List_inst1 B) (H : I.List_Mem_inst1 B a l) : StrictlyInhabited (d a \in cl1_unmap d l) :=
  match H with
  | I.List_Mem_head_inst1 l' => strictly_inhabits (mem_head (d a) (cl1_unmap d l'))
  | I.List_Mem_tail_inst1 y l' Ht =>
      match cl1_mem_backward a l' Ht with
      | strictly_inhabits Hm => strictly_inhabits (introT orP (or_intror Hm) : d a \in d y :: cl1_unmap d l')
      end
  end.

Lemma cl1_mem_rel x s : PropSPropRel (x \in s) (I.List_Mem_inst1 B (c x) (cl1_map c s)).
Proof.
  apply prop_sprop_rel_intro; first exact (cl1_mem_forward x s).
  intro H. have S := cl1_mem_backward _ _ H. rewrite Hdc (cl1_unmap_map c d Hdc) in S. exact S.
Qed.

Lemma cl1_mem_rel_list x s sL : ClListRel1 c s sL -> PropSPropRel (x \in s) (I.List_Mem_inst1 B (c x) sL).
Proof. intro H. destruct H. exact (cl1_mem_rel x s). Qed.

Lemma cl1_notin_rel x s sL : ClListRel1 c s sL ->
  PropSPropRel (is_true (x \notin s)) (I.Not (I.List_Mem_inst1 B (c x) sL)).
Proof.
  intro H. have M := cl1_mem_rel_list x s sL H. apply prop_sprop_rel_intro.
  - move=> /negP N HL. exact (ct_coq_false_to_target (N (sprop_to_prop _ _ M HL))).
  - intro N. apply strictly_inhabits. apply/negP => Hm.
    exact (interpret_strict _ (ct_target_false_to_strict (N (prop_to_sprop _ _ M Hm)))).
Qed.

End Eq.

Section EqU.
Variables (A : eqType) (B : Type) (c : A -> B) (d : B -> A).
Hypothesis Hdc : forall x, Logic.eq (d (c x)) x.
Hypothesis Hcd : forall y, Logic.eq (c (d y)) y.

Fixpoint cl1_uniq_forward (s : seq A) : uniq s -> I.List_Nodup_inst1 B (cl1_map c s).
Proof.
  destruct s as [|x s]; cbn.
  - intros _. exact (I.List_Pairwise_nil_inst1 B (I.Ne B)).
  - intro H. destruct (andb_prop _ _ H) as [Hx Hs]. apply I.List_Pairwise_cons_inst1.
    + intros y Hy Exy.
      have Hy' := interpret_strict _ (cl1_mem_backward A B d _ _ Hy).
      rewrite (cl1_unmap_map c d Hdc) in Hy'.
      have E := imported_eq_to_coq_eq _ _ Exy. rewrite -E Hdc in Hy'.
      have F : Logic.False by rewrite Hy' in Hx.
      exact (ct_coq_false_to_target F).
    + exact (cl1_uniq_forward s Hs).
Defined.

Lemma cl1_uniq_backward (l : I.List_inst1 B) : I.List_Nodup_inst1 B l -> StrictlyInhabited (uniq (cl1_unmap d l)).
Proof.
  intro H. induction H as [|y l Hpair Htail IH].
  - exact (strictly_inhabits (Logic.eq_refl true)).
  - destruct IH as [IHu]. apply strictly_inhabits. rewrite /= IHu andbT. apply/negP => Hm.
    have Hm' := cl1_mem_forward A B c _ _ Hm. rewrite (cl1_map_unmap c d Hcd) Hcd in Hm'.
    exact (interpret_strict _ (ct_target_false_to_strict (Hpair y Hm' (@Lean.eq_refl _ _)))).
Qed.

Lemma cl1_uniq_rel s : PropSPropRel (uniq s) (I.List_Nodup_inst1 B (cl1_map c s)).
Proof.
  apply prop_sprop_rel_intro; first exact (cl1_uniq_forward s).
  intro H. have S := cl1_uniq_backward _ H. rewrite (cl1_unmap_map c d Hdc) in S. exact S.
Qed.

Lemma cl1_uniq_rel_list s sL : ClListRel1 c s sL -> PropSPropRel (uniq s) (I.List_Nodup_inst1 B sL).
Proof. intro H. destruct H. exact (cl1_uniq_rel s). Qed.


End EqU.

