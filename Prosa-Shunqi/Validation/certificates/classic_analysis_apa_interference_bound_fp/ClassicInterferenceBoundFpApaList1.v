(** * Conversions *)

Fixpoint cl1_map {A B : Type} (c : A -> B) (s : seq A) : I.List_inst1 B :=
  match s with [::] => I.List_nil_inst1 B | x :: s' => I.List_cons_inst1 B (c x) (cl1_map c s') end.

Fixpoint cl1_unmap {A B : Type} (d : B -> A) (l : I.List_inst1 B) : seq A :=
  match l with I.List_nil_inst1 => [::] | I.List_cons_inst1 x l' => d x :: cl1_unmap d l' end.

Lemma cl1_unmap_map {A B : Type} (c : A -> B) (d : B -> A) (Hdc : forall x, Logic.eq (d (c x)) x) s :
  Logic.eq (cl1_unmap d (cl1_map c s)) s.
Proof. elim: s => [|x s IH] //=. by rewrite Hdc IH. Qed.

Lemma cl1_map_unmap {A B : Type} (c : A -> B) (d : B -> A) (Hcd : forall y, Logic.eq (c (d y)) y) l :
  Logic.eq (cl1_map c (cl1_unmap d l)) l.
Proof. induction l as [|y l IH]; first reflexivity. cbn. by rewrite Hcd IH. Qed.

Definition ClListRel1 {A B : Type} (c : A -> B) (sR : seq A) (sL : I.List_inst1 B) : SProp := Lean.eq (cl1_map c sR) sL.

Lemma cl1_list_logic {A B} (c : A -> B) sR sL : ClListRel1 c sR sL -> Logic.eq sL (cl1_map c sR).
Proof. intro H. exact (Logic.eq_sym (imported_eq_to_coq_eq _ _ H)). Qed.

Lemma cl1_forall_list {A B : Type} (c : A -> B) (d : B -> A) (Hcd : forall y, Logic.eq (c (d y)) y)
    (PR : seq A -> Prop) (PL : I.List_inst1 B -> SProp) :
  (forall sR sL, ClListRel1 c sR sL -> PropSPropRel (PR sR) (PL sL)) ->
  PropSPropRel (forall s, PR s) (forall s, PL s).
Proof.
  intro H. apply prop_sprop_rel_intro.
  - intros HR sL.
    exact (prop_to_sprop _ _ (H _ _ (cl1_lean_eq _ _ _ (cl1_map_unmap c d Hcd sL))) (HR _)).
  - intro HL. apply strictly_inhabits. intro sR.
    exact (sprop_to_prop _ _ (H sR (cl1_map c sR) (@Lean.eq_refl _ _)) (HL _)).
Qed.


