Lemma co_ord_eq_rel nR nL o1 o2 l1 l2 : CoOrdRel nR nL o1 l1 -> CoOrdRel nR nL o2 l2 ->
  PropSPropRel (Logic.eq o1 o2) (Lean.eq l1 l2).
