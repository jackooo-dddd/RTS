Lemma co_exists_ord nR nL (Hn : SubNatRel nR nL) (PR : 'I_nR -> Prop) (PL : Fin nL -> SProp) :
  (forall oR oL, CoOrdRel nR nL oR oL -> PropSPropRel (PR oR) (PL oL)) -> PropSPropRel (exists o, PR o) (I.Exists (Fin nL) PL).
