      (I.List_range' (sub_nat_to_imported (S s)) (sub_nat_to_imported n) co_one))
    (I.List_cons_inst1 _ (sub_nat_to_imported s) (co_natl (iota (S s) n)))).
  by rewrite IH.
Qed.

