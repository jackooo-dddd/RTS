(** * Conversions *)

Fixpoint cl_map {A B : Type} (c : A -> B) (s : seq A) : I.List B :=
  match s with [::] => I.List_nil B | x :: s' => I.List_cons B (c x) (cl_map c s') end.

Fixpoint cl_unmap {A B : Type} (d : B -> A) (l : I.List B) : seq A :=
  match l with I.List_nil => [::] | I.List_cons x l' => d x :: cl_unmap d l' end.

Lemma cl_unmap_map {A B : Type} (c : A -> B) (d : B -> A) (Hdc : forall x, Logic.eq (d (c x)) x) s :
  Logic.eq (cl_unmap d (cl_map c s)) s.
Proof. elim: s => [|x s IH] //=. by rewrite Hdc IH. Qed.

Lemma cl_map_unmap {A B : Type} (c : A -> B) (d : B -> A) (Hcd : forall y, Logic.eq (c (d y)) y) l :
  Logic.eq (cl_map c (cl_unmap d l)) l.
Proof. induction l as [|y l IH]; first reflexivity. cbn. by rewrite Hcd IH. Qed.

Definition ClListRel {A B : Type} (c : A -> B) (sR : seq A) (sL : I.List B) : SProp := Lean.eq (cl_map c sR) sL.

Lemma cl_list_logic {A B} (c : A -> B) sR sL : ClListRel c sR sL -> Logic.eq sL (cl_map c sR).
Proof. intro H. exact (Logic.eq_sym (imported_eq_to_coq_eq _ _ H)). Qed.

Lemma cl_forall_list {A B : Type} (c : A -> B) (d : B -> A) (Hcd : forall y, Logic.eq (c (d y)) y)
    (PR : seq A -> Prop) (PL : I.List B -> SProp) :
  (forall sR sL, ClListRel c sR sL -> PropSPropRel (PR sR) (PL sL)) ->
  PropSPropRel (forall s, PR s) (forall s, PL s).
Proof.
  intro H. apply prop_sprop_rel_intro.
  - intros HR sL.
    exact (prop_to_sprop _ _ (H _ _ (cl_lean_eq _ _ _ (cl_map_unmap c d Hcd sL))) (HR _)).
  - intro HL. apply strictly_inhabits. intro sR.
    exact (sprop_to_prop _ _ (H sR (cl_map c sR) (@Lean.eq_refl _ _)) (HL _)).
Qed.

Lemma cl_exists_list {A B : Type} (c : A -> B) (d : B -> A) (Hcd : forall y, Logic.eq (c (d y)) y)
    (PR : seq A -> Prop) (PL : I.List B -> SProp) :
  (forall sR sL, ClListRel c sR sL -> PropSPropRel (PR sR) (PL sL)) ->
  PropSPropRel (exists s, PR s) (I.Exists (I.List B) PL).
Proof.
  intro H. apply prop_sprop_rel_intro.
  - intros [sR HsR]. exact (I.Exists_intro _ PL (cl_map c sR) (prop_to_sprop _ _ (H _ _ (@Lean.eq_refl _ _)) HsR)).
  - intros [sL HsL]. apply strictly_inhabits. exists (cl_unmap d sL).
    exact (sprop_to_prop _ _ (H _ _ (cl_lean_eq _ _ _ (cl_map_unmap c d Hcd sL))) HsL).
Qed.

Definition cl_opt {A : Type} (o : option A) : I.Option A :=
  if o is Some x then I.Option_some A x else I.Option_none A.
Definition cl_unopt {A : Type} (o : I.Option A) : option A :=
  match o with I.Option_some x => Some x | I.Option_none => None end.
Lemma cl_unopt_opt {A} (o : option A) : Logic.eq (cl_unopt (cl_opt o)) o. Proof. by case: o. Qed.
Lemma cl_opt_unopt {A} (o : I.Option A) : Logic.eq (cl_opt (cl_unopt o)) o. Proof. by case: o. Qed.

Lemma cl_size {A B} (c : A -> B) s : SubNatRel (size s) (I.List_length B (cl_map c s)).
Proof. apply: cl_lean_eq. elim: s => [|x s IH] //=. by rewrite IH. Qed.

Lemma cl_cat {A B} (c : A -> B) s1 s2 :
  Logic.eq (cl_map c (s1 ++ s2))
    (I.HAppend_hAppend (I.List B) (I.List B) (I.List B) (I.instHAppendOfAppend (I.List B) (I.List_instAppend B))
       (cl_map c s1) (cl_map c s2)).
Proof. elim: s1 => [|x s1 IH] //=. by rewrite IH. Qed.

Lemma cl_rcons {A B} (c : A -> B) s x :
  Logic.eq (cl_map c (rcons s x))
    (I.HAppend_hAppend (I.List B) (I.List B) (I.List B) (I.instHAppendOfAppend (I.List B) (I.List_instAppend B))
       (cl_map c s) (I.List_cons B (c x) (I.List_nil B))).
Proof. by rewrite -cats1 cl_cat. Qed.

Lemma cl_map_op {A B A' B'} (c : A -> B) (c' : A' -> B') (fR : A -> A') (fL : B -> B')
    (Hf : forall x, Logic.eq (fL (c x)) (c' (fR x))) s :
  Logic.eq (cl_map c' (map fR s)) (I.List_map B B' fL (cl_map c s)).
Proof. elim: s => [|x s IH] //=. rewrite IH -Hf. reflexivity. Qed.

Lemma cl_filter {A B} (c : A -> B) (pR : A -> bool) (pL : B -> I.Bool)
    (Hp : forall x, CtBoolRel (pR x) (pL (c x))) s :
  Logic.eq (cl_map c (filter pR s)) (I.List_filter B pL (cl_map c s)).
Proof.
  elim: s => [|x s IH] //=.
  have -> : Logic.eq (I.List_filter B pL (I.List_cons B (c x) (cl_map c s)))
      (match pL (c x) with
       | I.Bool_true => I.List_cons B (c x) (I.List_filter B pL (cl_map c s))
       | I.Bool_false => I.List_filter B pL (cl_map c s) end).
  { cbn. destruct (pL (c x)); reflexivity. }
  rewrite (ct_bool_rel_logic _ _ (Hp x)) -IH. by case: (pR x).
Qed.

Lemma cl_take {A B} (c : A -> B) : forall n s,
  Logic.eq (cl_map c (take n s)) (I.List_take B (sub_nat_to_imported n) (cl_map c s)).
Proof. elim => [|n IH] [|x s] //=. by rewrite IH. Qed.

